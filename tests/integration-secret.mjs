import assert from "node:assert/strict";
import fs from "node:fs";
import { build } from "esbuild";
import { createRequire } from "node:module";
fs.mkdirSync(".server-runtime", { recursive: true });
await build({ entryPoints: ["lib/integration-secret.ts"], outfile: ".server-runtime/integration-secret.cjs", platform: "node", format: "cjs", bundle: true });
const { encryptIntegrationToken: encrypt, decryptIntegrationToken: decrypt } = createRequire(import.meta.url)("../.server-runtime/integration-secret.cjs");
const secret = "a".repeat(48), token = "private-fixture-token";
const first = encrypt("client-one", token, secret), second = encrypt("client-one", token, secret);
assert.notEqual(first, second, "fresh nonce per save");
assert.ok(!first.includes(token), "plaintext is absent from ciphertext");
assert.equal(decrypt("client-one", first, secret), token);
assert.throws(() => decrypt("client-two", first, secret), /could not be read/);
assert.throws(() => decrypt("client-one", first, "b".repeat(48)), /could not be read/);
const parts = first.split("."); parts[2] = Buffer.alloc(16).toString("base64url");
assert.throws(() => decrypt("client-one", parts.join("."), secret), /could not be read/);
for (const value of ["", "v2.x.x.x", "v1.x.x.x", first + ".extra"]) assert.throws(() => decrypt("client-one", value, secret));
assert.throws(() => encrypt("client-one", token, "short"));
console.log("Integration token encryption, client binding, tamper rejection and key checks passed.");
