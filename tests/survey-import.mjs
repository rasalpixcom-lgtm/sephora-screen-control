import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { build } from "esbuild";
const compiled = await build({ entryPoints: ["lib/survey-import.ts"], bundle: true, format: "esm", platform: "node", write: false });
const { parseSurveyText, surveyWarnings } = await import("data:text/javascript;base64," + Buffer.from(compiled.outputFiles[0].text).toString("base64"));
const fixture = name => fs.readFile(new URL(`./fixtures/survey-${name}.txt`, import.meta.url), "utf8");
const ledText = await fixture("led"), lcdText = await fixture("lcd"), wallText = await fixture("video-wall");
const led = parseSurveyText(ledText), lcd = parseSurveyText(lcdText), wall = parseSurveyText(wallText);
assert.equal(led.screenType, "LED");
assert.deepEqual(Object.keys(led.hardware), ["ledDisplay", "ledController", "mediaPlayer", "powerNetwork"]);
assert.equal(led.hardware.ledDisplay.resolution, "2000 × 800");
assert.equal(led.hardware.ledDisplay.total_sqm, "10");
assert.equal(led.hardware.ledDisplay.totalSqm, undefined);
assert.equal(led.hardware.ledDisplay.dimensions, undefined);
assert.equal(led.hardware.ledController.sending_card_serial, "2ABD23612W0A10018537");
assert.equal(led.hardware.ledController.novalct_connected, "Yes");
assert.equal(led.hardware.ledController.rgb_mixing, undefined);
assert.equal(led.hardware.mediaPlayer.labelled, "No");
assert.equal(led.hardware.mediaPlayer.model, "P388");
assert.equal(led.hardware.powerNetwork.quantity, "40");
assert.equal(led.ppm.network_cables, "Fail");
assert.equal(led.ppm.overallStatus, "Pass");
assert.equal(led.ppm.ppmDate, "2026-11-02");
assert.equal(led.ppm.nextPpmDate, undefined);
assert.equal(led.ppm.correctiveAction, undefined);
assert.ok(led.skipped > 20);
assert.deepEqual(lcd.hardware, { lcd: { tv_model: "QM32R", tv_size: "32", manufactured_by: "Samsung", installed_by: "Sephora" } });
assert.equal(lcd.ppm.led_modules, undefined);
assert.equal(wall.hardware.video_wall.display_qty, "25");
assert.equal(wall.hardware.video_wall.total_width_mm, "6500");
assert.equal(wall.hardware.video_wall.resolution, undefined);
assert.ok(surveyWarnings(led, led.source.split(" — ")[0], "LED", led.ppm).some(text => text.includes("resolution")));
assert.ok(surveyWarnings(wall, "Another screen", "LED", wall.ppm).length >= 3);
assert.deepEqual(parseSurveyText(lcdText.replace(/\n/g, "\r\n")), lcd);
const multiline = lcdText.replace("Defects / findings:", "Defects / findings: First line\nSecond line: details\n\nThird paragraph").replace("Corrective action:", "Corrective action:\nInspect network\nContact: IT team");
assert.equal(parseSurveyText(multiline).ppm.findings, "First line\nSecond line: details\n\nThird paragraph");
assert.equal(parseSurveyText(multiline).ppm.correctiveAction, "Inspect network\nContact: IT team");
for (const invalid of ["", lcdText + "\n" + lcdText, lcdText.replace("LCD TV model: QM32R", "Unexpected field: value"), lcdText.replace("Screen type: LCD", "Screen type: LED"), lcdText.replace("PPM date: 2026-11-01", "PPM date: 2026-02-30"), lcdText.replace("LCD TV size (inches): 32", "LCD TV size (inches): -1"), ledText.replace("Screen height (pixels): 800", "Screen height (pixels):"), lcdText.replace("Screen type: LCD", "Screen type: Projector"), "x".repeat(24001)]) assert.throws(() => parseSurveyText(invalid));
console.log("Survey parser checks passed for LED, LCD, Video Wall, multiline notes and invalid input.");
